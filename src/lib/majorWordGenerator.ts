// Letter normalizer: extract base Hebrew letters from a consonants string like "ס, ז, שׂ" or "א" or "ב/פ דגושה"
export function extractHebrewLetters(consonantStr: string): string[] {
  if (!consonantStr) return [];
  // Remove non-hebrew characters except slashes or commas
  const cleaned = consonantStr
    .replace(/דגושה|רפה|שמאלית|ימנית/g, '')
    .trim();
  
  const matches = cleaned.match(/[\u0590-\u05FF]/g) || [];
  const unique = Array.from(new Set(matches)).filter(
    (ch) => ch >= 'א' && ch <= 'ת'
  );
  return unique.length > 0 ? unique : ['א'];
}

