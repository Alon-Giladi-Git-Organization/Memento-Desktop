// Fallback generator for any letter pair not explicitly listed or unknown
function getFallbackWordAndHint(letter1: string, letter2: string): WordHint {
  // Try finding in standard dictionary or create an intuitive Hebrew word
  const l1 = letter1 || 'א';
  const l2 = letter2 || 'א';
  return {
    word: `${l1}${l2}`,
    hint: `סמל מנמוני של ${l1} ו-${l2} זוהרים באור קסום ומתנגשים בעוצמה`,
  };
}

/**
 * Finds the best Hebrew mnemonic word and visual kinetic hint for a pair of letters (or single digit).
 */
export function generateWordForConsonants(
  tensConsonants: string,
  unitsConsonants: string,
  number: number
): { word: string; hint: string; consonantsStr: string } {
  // If tensConsonants is empty (e.g. single digit 0-9), look for single-letter or duplicate letter combo
  if (!tensConsonants && unitsConsonants) {
    const letters = extractHebrewLetters(unitsConsonants);
    const cleanUnits = letters.join('/') || unitsConsonants;
    for (const u of letters) {
      const selfKey = `${u}_${u}`;
      if (LETTER_PAIR_VOCAB[selfKey] && LETTER_PAIR_VOCAB[selfKey].length > 0) {
        const options = LETTER_PAIR_VOCAB[selfKey];
        const pick = options[number % options.length];
        return { word: pick.word, hint: pick.hint, consonantsStr: cleanUnits };
      }
    }
    const firstLetter = letters[0] || 'א';
    const fallback = getFallbackWordAndHint(firstLetter, firstLetter);
    return { word: fallback.word, hint: fallback.hint, consonantsStr: cleanUnits };
  }

  const tensLetters = extractHebrewLetters(tensConsonants);
  const unitsLetters = extractHebrewLetters(unitsConsonants);

  // Clean formatted consonants representation
  const cleanTens = tensLetters.join('/') || tensConsonants;
  const cleanUnits = unitsLetters.join('/') || unitsConsonants;
  const consonantsStr = tensLetters.length > 0 ? `${cleanTens} + ${cleanUnits}` : cleanUnits;

  // Prefer curated canonical word if default consonants match
  const defaultEntry = DEFAULT_MAJOR_00_99.find((d) => d.number === number);
  if (defaultEntry && defaultEntry.consonants) {
    const entryLetters = extractHebrewLetters(defaultEntry.consonants);
    const tensMatch = tensLetters.length === 0 || tensLetters.some((t) => entryLetters.includes(t));
    const unitsMatch = unitsLetters.some((u) => entryLetters.includes(u));
    if (tensMatch && unitsMatch) {
      return {
        word: defaultEntry.defaultWord,
        hint: defaultEntry.imageHint,
        consonantsStr,
      };
    }
  }

  // Try all combinations of letters from tens and units
  for (const t of tensLetters) {
    for (const u of unitsLetters) {
      const key = `${t}_${u}`;
      if (LETTER_PAIR_VOCAB[key] && LETTER_PAIR_VOCAB[key].length > 0) {
        // Pick an item deterministically based on number
        const options = LETTER_PAIR_VOCAB[key];
        const pick = options[number % options.length];
        return {
          word: pick.word,
          hint: pick.hint,
          consonantsStr,
        };
      }
    }
  }

  // Also try reversed or alternative (e.g. if single letter exists like 'ס_א' for 'א_ס')
  for (const t of tensLetters) {
    for (const u of unitsLetters) {
      const revKey = `${u}_${t}`;
      if (LETTER_PAIR_VOCAB[revKey] && LETTER_PAIR_VOCAB[revKey].length > 0) {
        const options = LETTER_PAIR_VOCAB[revKey];
        const pick = options[number % options.length];
        return {
          word: pick.word,
          hint: pick.hint,
          consonantsStr,
        };
      }
    }
  }

  // Fallback
  const fallback = getFallbackWordAndHint(tensLetters[0], unitsLetters[0]);
  return {
    word: fallback.word,
    hint: fallback.hint,
    consonantsStr,
  };
}
